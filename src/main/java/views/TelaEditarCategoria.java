    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        try {
            Categoria registro = new Categoria();
            registro.setNome_categoria(txtNome.getText());

            registro.setId_categoria(idRegistro);
            new CategoriaDAO().atualizar(registro);
            ApoioTela.sucesso(this, "Categoria atualizada com sucesso.");
            ApoioTela.abrir(this, TelaListarCategoria::new);
        } catch (RuntimeException ex) { ApoioTela.erro(this, ex); }
    }//GEN-LAST:event_btnSalvarActionPerformed

